using UnityEngine;

namespace Igruha.Minigames.HoleInWall
{
    /// <summary>
    /// Палитра «Дырки в стене» — подфаза 4.2. Один источник цвета на всю игру:
    /// арену строит редактор, стену и контуры вырезов собирает рантайм, и цвета
    /// у них обязаны совпадать.
    ///
    /// Значения взяты из арт-брифа (спека, раздел 14), а не подобраны на глаз:
    /// тёмный пол и фермы <c>#1A1A20</c>, белый глянцевый пластик платформ и
    /// стены <c>#E8E8EC</c>, неон <c>#FF2E88</c> и <c>#22D3EE</c>, бирюзовая
    /// полупрозрачная вода <c>#1FB6C1</c>.
    ///
    /// <b>Свечение — только у контура выреза и подсветки.</b> Пол половин
    /// красится, но не светится: светящийся пол спорит с контуром, а контур
    /// здесь единственное, что обязано читаться с 30 ШП (бриф).
    ///
    /// <b>Чего в палитре нет.</b> Цвета поз (<see cref="PlayerPoseAbility"/>) —
    /// не палитра, а игровой код: четыре позы должны различаться между собой,
    /// и двух неонов брифа на это не хватает. Их трогать не нужно.
    /// </summary>
    public static class HoleInWallPalette
    {
        /// <summary>Тёмный тон студии: пол, дно бассейна, фермы. Бриф, <c>#1A1A20</c>.</summary>
        public static readonly Color Stage = FromHex(0x1A, 0x1A, 0x20);

        /// <summary>Белый глянцевый пластик: настил платформы и плита стены. Бриф, <c>#E8E8EC</c>.</summary>
        public static readonly Color Plastic = FromHex(0xE8, 0xE8, 0xEC);

        /// <summary>Неон розово-малиновый. Бриф, <c>#FF2E88</c>.</summary>
        public static readonly Color NeonPink = FromHex(0xFF, 0x2E, 0x88);

        /// <summary>Неон голубой. Бриф, <c>#22D3EE</c>.</summary>
        public static readonly Color NeonCyan = FromHex(0x22, 0xD3, 0xEE);

        /// <summary>
        /// Вода бассейна. Бриф, <c>#1FB6C1</c>.
        ///
        /// Альфа — не украшение: сквозь неё обязано просвечивать тёмное дно,
        /// иначе бассейн читается крашеным полом и глубина падения пропадает
        /// вместе с ценой ошибки. На 0.62 дно не пробивалось вовсе — вода
        /// выходила сплошной бирюзовой плитой.
        /// </summary>
        public static readonly Color Water = new Color(0x1F / 255f, 0xB6 / 255f, 0xC1 / 255f, 0.45f);

        /// <summary>
        /// Сталь лесенки. В брифе её нет: лесенка — декор, и палитра ей цвета не
        /// назначает. Замер пака здесь не годится — родная модель
        /// (<c>#584633</c>) это ржавое дерево, к ночной студии отношения не
        /// имеющее. Взята нейтраль ровно посередине между <see cref="Stage"/> и
        /// <see cref="Plastic"/> по линейной яркости, с холодным сдвигом в
        /// сторону голубого неона.
        /// </summary>
        public static readonly Color Metal = FromHex(0xA2, 0xA8, 0xB0);

        /// <summary>
        /// Насколько неон подмешан в пластик пола половин.
        ///
        /// Не единица: половины — разметка, а не подсветка, и чистый неон под
        /// ногами перебивал бы контур выреза, который обязан читаться первым.
        ///
        /// Но и не 0.45, с которых начинали: на такой примеси голубая половина
        /// выходила бледной и с уровня глаз игрока сливалась с водой бассейна —
        /// а по брифу игрок обязан различать «своё место» и «внизу вода» обоими
        /// глазами сразу. Разводит их насыщенность, а не тон.
        /// </summary>
        public const float FloorTint = 0.62f;

        /// <summary>Своя половина пола пары.</summary>
        public static readonly Color FloorOwn = Color.Lerp(Plastic, NeonPink, FloorTint);

        /// <summary>Половина пола партнёра.</summary>
        public static readonly Color FloorPartner = Color.Lerp(Plastic, NeonCyan, FloorTint);

        /// <summary>Глянец пластика: бриф требует именно глянцевый, а не матовый.</summary>
        public const float PlasticSmoothness = 0.78f;

        /// <summary>Матовость тёмного пола: блик на полу студии крал бы контраст с платформой.</summary>
        public const float StageSmoothness = 0.18f;

        /// <summary>Металличность стали лесенки.</summary>
        public const float MetalMetallic = 0.85f;

        /// <summary>Глянец стали лесенки.</summary>
        public const float MetalSmoothness = 0.62f;

        /// <summary>Глянец воды: почти зеркало, иначе бассейн читается крашеным полом.</summary>
        public const float WaterSmoothness = 0.92f;

        /// <summary>
        /// Во сколько раз свечение неона ярче его же цвета.
        ///
        /// Единица — это «светится ровно своим цветом», и выше её сейчас
        /// поднимать нечем. В сцене нет ни тонмаппинга, ни bloom: всё, что
        /// ярче единицы, URP просто срезает по каналам. На 3.2 голубой неон
        /// отрисовывался как <c>#50FFFF</c>, а розовый как <c>#FF64FE</c> —
        /// то есть цвет контура переставал быть цветом и становился засветкой,
        /// а контур обязан читаться и силуэтом, и цветом.
        ///
        /// Поднять яркость — задача подфазы 4.3, и там она решается не этим
        /// числом, а Volume с тонмаппингом и bloom. До тех пор палитра
        /// настроена так, чтобы не врать про цвет.
        /// </summary>
        public const float NeonEmission = 1f;

        private static Color FromHex(int r, int g, int b)
        {
            return new Color(r / 255f, g / 255f, b / 255f);
        }
    }
}
