namespace Igruha.Minigames.HoleInWall
{
    /// <summary>
    /// Поза игрока в «Дырке в стене». Ровно четыре, по клавишам 1–4
    /// (спека, раздел 4). Значения фиксированы и совпадают с номерами клавиш:
    /// по ним же сравниваются поза игрока и поза выреза, и они же уедут
    /// в <c>NetworkVariable</c> в фазе 3 — отсюда явный <c>byte</c>.
    /// </summary>
    public enum HoleInWallPose : byte
    {
        /// <summary>Позы нет: игрок ещё ничего не нажал. Ни одному вырезу не подходит.</summary>
        None = 0,

        /// <summary>1 — руки вверх: узкий вертикальный силуэт.</summary>
        HandsUp = 1,

        /// <summary>2 — руки в стороны: широкий крест.</summary>
        HandsWide = 2,

        /// <summary>3 — присед: низкий компактный силуэт. Единственная поза, у которой уже есть клип.</summary>
        Crouch = 3,

        /// <summary>4 — выпад вбок: асимметричный силуэт, отражается вместе с вырезом.</summary>
        SideLunge = 4
    }
}
