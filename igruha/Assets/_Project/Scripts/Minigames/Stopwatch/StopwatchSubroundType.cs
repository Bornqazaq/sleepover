namespace Igruha.Minigames.Stopwatch
{
    /// <summary>
    /// Тип подраунда. Меняет не сложность, а характер риска — потому механика
    /// и не приедается за восемь подраундов.
    /// </summary>
    public enum StopwatchSubroundType
    {
        /// <summary>А — «отмерь ровно N секунд». Хуже тот, у кого больше модуль отклонения.</summary>
        Precision = 0,
        /// <summary>Б — «не больше N секунд». Хуже нарушители, за ними — кто остановился раньше всех.</summary>
        Ceiling = 1,
        /// <summary>В — «не меньше N секунд». Хуже нарушители, за ними — кто перебрал сильнее всех.</summary>
        Floor = 2
    }
}
