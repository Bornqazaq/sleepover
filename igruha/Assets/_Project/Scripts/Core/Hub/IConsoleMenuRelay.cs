namespace Igruha.Core.Hub
{
    /// <summary>
    /// Куда экран приставки отдаёт решения хоста, когда идёт сетевая катка.
    ///
    /// Меню — общее на всю комнату: его видят все, а трогает только хост.
    /// Значит состояние (открыто ли, что подсвечено) обязано жить на сервере
    /// и приезжать остальным, а не считаться у каждого по-своему.
    ///
    /// Core про NGO ничего не знает, поэтому шов здесь, а реализация — в
    /// сетевом слое; она сама себя регистрирует, как это уже сделано для
    /// выбора персонажа. Пусто — сети нет, и меню работает целиком на месте.
    /// </summary>
    public interface IConsoleMenuRelay
    {
        /// <summary>Эта машина решает: одиночная сцена или хост.</summary>
        bool HasAuthority { get; }

        /// <summary>Разослать всем: приставка включена/выключена.</summary>
        void SetMenuOpen(bool open);

        /// <summary>Разослать всем: подсвечена игра под этим номером.</summary>
        void SetCursor(int index);

        /// <summary>
        /// Показать новому экрану то, что уже происходит. Хаб перезагружается
        /// между мини-играми, а состояние меню живёт дольше сцены: без этого
        /// экран, собранный посреди выбора, стоял бы тёмным.
        /// </summary>
        void SyncScreen();
    }
}
