using Igruha.Core.Minigame;

namespace Igruha.Core.CameraSystems
{
    /// <summary>
    /// Своя точка обзора игрока — для трансляции наблюдателю.
    ///
    /// Обычному персонажу этот шов не нужен: он смотрит туда же, куда развёрнут,
    /// и наблюдателю хватает поворота тела. Нужен он ролям, у которых обзор с
    /// телом не совпадает, — прежде всего первому лицу: там взгляд задаётся
    /// отдельными углами, и тело о наклоне ничего не знает.
    ///
    /// Вешается на аватар той ролью, которой это касается, и позволяет
    /// <see cref="SpectatorCamera"/> оставаться в стороне от правил игры.
    /// </summary>
    public interface ISpectatorView
    {
        /// <summary>
        /// Чем и куда смотрит этот игрок. <c>false</c> — своей точки обзора у
        /// него сейчас нет, наблюдателю смотреть за ним как за обычным.
        /// </summary>
        bool TryGetView(out CameraMode mode, out float yaw, out float pitch);
    }
}
