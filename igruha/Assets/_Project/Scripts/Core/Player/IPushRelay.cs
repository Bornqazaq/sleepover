using UnityEngine;

namespace Igruha.Core.Player
{
    /// <summary>
    /// Посредник, передающий толчок цели через сеть.
    ///
    /// Толкать чужого персонажа напрямую нельзя: его позицией распоряжается
    /// машина владельца и локальное изменение будет тут же перетёрто. Сетевой
    /// слой реализует этот интерфейс и доставляет запрос владельцу цели.
    /// В одиночной игре реализации нет — толчок применяется напрямую.
    /// </summary>
    public interface IPushRelay
    {
        /// <summary>
        /// Передать толчок по сети. Возвращает false, если передать не удалось
        /// (нет сети, цель не сетевая) — тогда вызывающий применяет толчок локально.
        /// </summary>
        bool TryRelayPush(PlayerController target, Vector3 direction, float force);
    }
}
