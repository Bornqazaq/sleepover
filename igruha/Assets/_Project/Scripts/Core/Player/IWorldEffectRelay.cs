using UnityEngine;

namespace Igruha.Core.Player
{
    /// <summary>
    /// Посредник для воздействий мира на персонажа: пружин, взрывов, зон смерти,
    /// снарядов. Сетевой слой реализует интерфейс, Core о сети не знает.
    ///
    /// Прямое воздействие ломается в сети по двум причинам. Триггер ловушки или
    /// зоны срабатывает на каждой машине матча, поэтому эффект применился бы
    /// столько раз, сколько в матче игроков. И позицией персонажа распоряжается
    /// машина его владельца, так что чужую копию всё равно тут же перетрёт
    /// сетевое состояние.
    ///
    /// В одиночной игре реализации нет — воздействие применяется напрямую.
    /// </summary>
    public interface IWorldEffectRelay
    {
        /// <summary>
        /// Вправе ли эта машина решать, что произошло с персонажем.
        /// В сетевой игре — только сервер.
        /// </summary>
        bool HasAuthority { get; }

        /// <summary>
        /// Отдать импульс сетевому слою. true — слой взял ответственность:
        /// сервер отправил владельцу либо машина решать не вправе.
        /// false — сеть не запущена, применять локально.
        /// </summary>
        bool TryRelayImpulse(Vector3 impulse);

        /// <summary>
        /// Отдать перенос сетевому слою. Контракт возврата тот же, что у импульса.
        /// </summary>
        bool TryRelayTeleport(Vector3 position, Quaternion rotation);
    }
}
