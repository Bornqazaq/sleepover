namespace Igruha.Core.Player
{
    /// <summary>
    /// Роль, забравшая себе кнопку толчка. Пока она стоит на персонаже,
    /// <see cref="PlayerPushAbility"/> не бьёт и не бросает предмет: нажатие
    /// целиком уходит сюда.
    ///
    /// Нужна там, где одна кнопка означает разное в зависимости от того, чем
    /// заняты руки. В «Переноске предмета» держащий бутыль не может ударить —
    /// зато может швырнуть саму бутыль, и швыряют её все несущие разом, то есть
    /// решение принимает не персонаж, а объект в его руках.
    ///
    /// Ставится и снимается тем, кто занял руки, — не самим персонажем: снимать
    /// обязан тот же, кто вешал, иначе роль уедет в хаб вместе с телом.
    /// </summary>
    public interface IPushButtonOverride
    {
        /// <summary>
        /// Игрок нажал кнопку толчка. Вернуть true — нажатие израсходовано,
        /// удар и бросок предмета не выполняются.
        /// </summary>
        bool HandlePushButton(PlayerController player);
    }
}
