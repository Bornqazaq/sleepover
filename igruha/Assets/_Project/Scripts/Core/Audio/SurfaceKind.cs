namespace Igruha.Core.Audio
{
    /// <summary>
    /// Поверхность под ногами — тем составом, в каком её прислала поставка звука.
    ///
    /// Список намеренно короткий и материальный: это не «типы пола в игре», а ровно
    /// те наборы шагов, которые есть в <c>Assets/_Project/Audio/Core/Character</c>.
    /// Добавлять значение имеет смысл только вместе с приехавшей пачкой файлов —
    /// иначе пол, помеченный несуществующей поверхностью, становится немым.
    /// </summary>
    public enum SurfaceKind
    {
        /// <summary>Бетон, плитка, камень: стройка, башня Duck Hunt, зал ангелов.</summary>
        Concrete = 0,

        /// <summary>Дерево: лестница хаба, клетки цирка, доски, школа.</summary>
        Wood = 1,

        /// <summary>Ковёр: хаб, казино.</summary>
        Carpet = 2,

        /// <summary>Металл: плиты «Рейса на память», решётки.</summary>
        Metal = 3,

        /// <summary>Трава и земля: ферма Duck Hunt, двор «Заражения».</summary>
        Grass = 4,

        /// <summary>Гравий и грунт: стройка; временно и песок.</summary>
        Gravel = 5,

        /// <summary>Снег: зимние этажи Duck Hunt.</summary>
        Snow = 6,
    }
}
